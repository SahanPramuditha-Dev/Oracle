import { test, expect } from '@playwright/test';
test('camera switching and face tracking', async ({ page }) => {
  await page.addInitScript(() => {
    localStorage.setItem('oracle_face_reticles', 'true');
    localStorage.setItem('oracle_show_all_objects', 'true');
    localStorage.setItem('oracle_yolo_enabled', 'true');
    (window as any).stopped = [];
    Object.defineProperty(navigator.mediaDevices, 'enumerateDevices', { value: async () => ['one', 'two', 'broken'].map(id => ({ kind: 'videoinput', deviceId: id, label: `Camera ${id}` })) });
    Object.defineProperty(navigator.mediaDevices, 'getUserMedia', { value: async (constraints: any) => {
      const id = constraints.video?.deviceId?.exact || 'one';
      if (id === 'broken') throw new Error('Unavailable');
      const canvas = document.createElement('canvas'); canvas.width = 640; canvas.height = 480;
      canvas.getContext('2d')!.fillRect(0, 0, 640, 480);
      const stream = canvas.captureStream(10), track = stream.getVideoTracks()[0];
      track.getSettings = () => ({ deviceId: id });
      const stop = track.stop.bind(track);
      track.stop = () => { (window as any).stopped.push(id); stop(); };
      return stream;
    } });
  });
  await page.route('**/api/v1/people/identify?*', r => r.fulfill({ json: { identified: [{ id: 'person', name: 'Test person', matched: true, recognition_state: 'recognized', cosine_score: .9, box: [100, 80, 120, 140] }, { id: null, name: '', matched: false, recognition_state: 'unknown', cosine_score: .1, box: [400, 100, 60, 80] }] } }));
  await page.route('**/api/v1/vision/detect?*', r => r.fulfill({ json: { detections: [{ class: 'scissors', confidence: .9, box: [250, 180, 90, 100] }] } }));
  await page.goto('/', { waitUntil: 'domcontentloaded' });
  await page.waitForFunction(() => Boolean(window.ORACLE));
  await page.keyboard.press('Escape');
  await page.evaluate(() => window.ORACLE?.setMode('ready'));
  await page.bringToFront();
  await page.getByTitle('Toggle optical vision feed', { exact: true }).click();
  const card = page.locator('.oracle-camera-card');
  await expect(card.locator('.camera-object-outline')).toContainText('SCISSORS');
  await expect(card.locator('.live-name-text').filter({ hasText: 'Test person' })).toBeVisible();
  await expect(card.locator('.camera-recognition-summary')).toHaveCount(0);
  await expect(card.locator('.live-name-text').filter({ hasText: 'Unidentified' })).toBeVisible();
  await expect(card.locator('.poi-target-container')).toHaveCount(2);
  await card.getByLabel('Camera settings', { exact: true }).click();
  await expect(card.getByText('Advanced settings', {exact:true})).toBeVisible();
  await expect(card.getByRole('button', {name:'Enroll face', exact:true})).toHaveCount(1);
  await card.screenshot({path:'test-results/camera-settings.png'});
  await card.getByLabel('Object detection').uncheck();
  await expect(card.locator('.camera-object-outline')).toHaveCount(0);
  await card.getByLabel('Object detection').check();
  await expect(card.locator('.camera-object-outline')).toContainText('SCISSORS');
  await card.getByLabel('Select camera').selectOption('two');
  await expect(card.getByLabel('Select camera')).toHaveValue('two');
  expect(await page.evaluate(() => (window as any).stopped)).toContain('one');
  await card.getByLabel('Select camera').selectOption('broken');
  await expect(card.getByRole('alert')).toContainText('Unable to open that camera');
  await expect(card.getByLabel('Select camera')).toHaveValue('two');
  expect(await page.evaluate(() => (window as any).stopped)).not.toContain('two');
  await card.getByLabel('Face detection').uncheck();
  await expect(card.locator('.poi-target-container')).toHaveCount(0);
  await card.getByLabel('Face detection').check();
  await card.getByLabel('Camera settings', { exact: true }).click();
  await expect(card.locator('.poi-target-container')).toHaveCount(2);
  await card.getByLabel('Close Camera Feed', { exact: true }).click();
  expect(await page.evaluate(() => (window as any).stopped)).toContain('two');
});
